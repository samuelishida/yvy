const I18nContext = createContext();

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('yvy-lang') || 'pt';
    } catch {
      return 'pt';
    }
  });

  const switchLang = useCallback((newLang) => {
    setLang(newLang);
    try {
      localStorage.setItem('yvy-lang', newLang);
    } catch {}
  }, []);

  const t = useCallback(
    (path, vars) => {
      const keys = path.split('.');
      let val = translations[lang];
      for (const key of keys) {
        val = val?.[key];
      }
      if (val === undefined) {
        let fallback = translations['pt'];
        for (const key of keys) {
          fallback = fallback?.[key];
        }
        val = fallback;
      }
      if (val === undefined || val === null) return path;
      if (vars && typeof val === 'string') {
        return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
      }
      return val;
    },
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, switchLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}